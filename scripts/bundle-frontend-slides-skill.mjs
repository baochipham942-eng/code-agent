// Bundle frontend-slides merge scripts so the packaged copies do not resolve
// pptxgenjs / pdf-lib from the repo node_modules tree.
// pptxgenjs is a root dependency. pdf-lib is not; point
// FRONTEND_SLIDES_EXTRA_NODE_PATH at a node_modules that contains it.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Entry sources live outside resources/skills so they never ship in the app bundle
// (release-security-scan flags any packaged /src/ tree). Only the generated
// .bundle.mjs outputs belong next to the wrappers in the packaged skill.
const skillSources = path.join(repoRoot, 'resources', 'skill-sources', 'frontend-slides');
const skillScripts = path.join(repoRoot, 'resources', 'skills', 'frontend-slides', 'scripts');
const extraNodePath = process.env.FRONTEND_SLIDES_EXTRA_NODE_PATH?.trim();
const nodePaths = [
  ...(extraNodePath ? [extraNodePath] : []),
  path.join(repoRoot, 'node_modules'),
];

const require = createRequire(path.join(repoRoot, 'package.json'));
function assertResolvable(name) {
  try {
    require.resolve(`${name}/package.json`, { paths: nodePaths });
    return;
  } catch {
    // pptxgenjs does not export package.json; resolving the package entry is enough.
  }
  try {
    require.resolve(name, { paths: nodePaths });
  } catch {
    console.error(`[bundle-frontend-slides] cannot resolve ${name} from: ${nodePaths.join(', ')}`);
    process.exit(1);
  }
}

assertResolvable('pptxgenjs');
assertResolvable('pdf-lib');

const entries = [
  ['merge-to-pptx-hybrid.mjs', 'merge-to-pptx-hybrid.bundle.mjs'],
  ['merge-to-pptx.mjs', 'merge-to-pptx.bundle.mjs'],
  ['merge-to-pdf.mjs', 'merge-to-pdf.bundle.mjs'],
];

for (const [input, output] of entries) {
  await esbuild.build({
    absWorkingDir: repoRoot,
    entryPoints: [path.join(skillSources, input)],
    bundle: true,
    platform: 'node',
    format: 'esm',
    outfile: path.join(skillScripts, output),
    nodePaths,
    legalComments: 'eof',
    banner: {
      js: '// Generated by scripts/bundle-frontend-slides-skill.mjs. Edit resources/skill-sources/frontend-slides, then regenerate.',
    },
    logLevel: 'info',
  });
  const outfile = path.join(skillScripts, output);
  const bundled = fs.readFileSync(outfile, 'utf8').replace(/[ \t]+$/gm, '');
  fs.writeFileSync(outfile, bundled);
}
