// ============================================================================
// startRun 的四种结果各自该对通话 brain 说什么。
//
// 单独成模块，是因为这四句话是「活到底开没开始」的唯一对外表述：通话 brain 拿它当
// 下一句的事实依据，收到「已经开始」就会对电话那头的人复述。留在 coordinator 里，
// 想验一句话得先构造账本 + 并发池两套状态的特定组合，构造成本远超被测逻辑本身。
//
// 2026-08-15 真机撞到的形状：同一个 startRun 结果在 delegateTask 与 steerTask 两处
// 各写一套处理，第二处只处理了 requires_choice——reused 与 queued 一起掉进
// 「我已经开始做了」，而活根本没开始。判据抄成两份，其中一份长歪。
// ============================================================================

export type VoiceStartRunOutcome = 'started' | 'queued' | 'reused' | 'requires_choice';

/**
 * 派活后回给通话 brain 的话（①）。三段缺一不可：
 * 1. 下一句台词（没有状态名词，无可润色空间）；
 * 2. 认知协议：结果只会以 [BACKEND] 消息送达，没收到就不存在「做完」；
 * 3. 进度问题强制落地 task_status，不许凭记忆答。
 */
function spawnSpeechDirective(title: string): string {
  return [
    // 台词写成**用户听得懂的第一人称**（E4，2026-07-30 真机）：上一版是
    // 「『X』这件事你开始做了，做完会立刻主动告诉他」——模型照着念出来，用户听到的是
    // 「你开始做了」，主语错乱、读不懂。「不要复述」类禁令本仓已三连败，所以不加禁令，
    // 改成即使被整句照读也通顺的话。
    `现在对用户说：「我已经开始做『${title}』了，做完马上告诉你。」就说这一个意思，不要再多说。`,
    '关于这件事你目前只知道「已经开始」。它的结果（做成或失败）只会以 [BACKEND] 开头的消息送达；',
    '在收到那条消息之前，它没有做完，你也不知道任何进展——不存在「应该差不多了」。',
    '用户如果问「好了吗」「怎么样了」，先调 task_status 看真实状态再回答，不要凭记忆或猜测回答。',
  ].join('\n');
}

/**
 * 四种结果 → 台词。**只有 started 允许说「已经开始做」**，其余三种这件活都还没跑一行。
 *
 * requires_choice 的选择框由调用方弹（那是副作用，不属于「该说什么」）；这里只保证
 * 话里不出现任何「已经开始」的说法。
 */
export function voiceStartRunSpeech(shortName: string, outcome: VoiceStartRunOutcome): string {
  if (outcome === 'reused') {
    return `「${shortName}」是本轮重复派发，已复用原任务（reused），没有再开第二件。`;
  }
  if (outcome === 'queued') {
    return `现在对用户说：「『${shortName}』已经排在同一条任务线后面，前一件结束就开始。」`;
  }
  if (outcome === 'requires_choice') {
    return '并发槽已经占满，已通过 AskUserQuestion 请用户选择排队或顶替哪一件；等待回答，不要替用户选。';
  }
  // 谎报的根治（批 X ①，2026-07-30）：上一版返回「已经排上队，还在后台跑，没做完。
  // 别说已经完成」——「已排队」是个可润色的状态名词，离「已完成」只差一次善意润色，
  // 真机第三次撞到模型照说「已经建好了」。禁令加狠话是同一招的第三次，不再走。
  // 换成言语行为指令 + 认知协议：返回值不描述状态，只说「你下一句该说什么」，
  // 并把「完成」从可推断的状态收窄成协议事件（只认 [BACKEND] 回流）。
  return spawnSpeechDirective(shortName);
}
