/**
 * 已连接源里出现日历类来源时，failed 措辞用「你的日历」，否则用「你的数据」
 * （2026-11-05 owner 返修：按角色实际连的源选措辞，不硬编码日历场景）。
 */
export function hasCalendarSource(sources: string[] | undefined): boolean {
  return (sources ?? []).some((name) => /日历|calendar/i.test(name));
}
